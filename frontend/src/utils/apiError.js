// apiErr 把后端错误响应({ key, detail })转成本地化文案。
//   err       axios 错误(或 catch 到的对象)
//   fallback  无 key 时的前端兜底文案。调用方传 _l('固定中文')，不要传动态 key。
// 返回: _l(key对应中文) + (detail ? ": "+detail : "")
export const apiErr = (err, fallback) => {
  const d = err && err.response && err.response.data;
  const base = (d && d.key && keyText(d.key)) || fallback || _l('操作失败');
  return d && d.detail ? `${base}: ${d.detail}` : base;
};
